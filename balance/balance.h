#ifndef __BALANCE_H
#define __BALANCE_H

#include <stdint.h>

/* ============================================================
 *  六足机器人 - spiderthree 陀螺仪自稳平衡模式
 * ------------------------------------------------------------
 *  流程：
 *    1. 蓝牙/AI 发送 spiderthree
 *    2. 自动切姿态2（全 90°）并等舵机到位
 *    3. 静止采样加速度计 ax/ay 作为水平基准（误差区间=死区）
 *    4. 之后小幅倾斜桌面：控制器按各腿前后/左右位置
 *       伸/缩腿（lift+knee 协调 ±Δ），把机身顶回水平
 *
 *  任意 spiderxxx 行走/姿态命令会自动退出平衡模式。
 * ============================================================ */

/* 启动平衡模式（切姿态2 -> 等舵机 -> 采基准 -> 闭环）
 * 返回应答字符串（由调用方发回蓝牙） */
const char *Balance_Start(void);

/* 退出平衡模式：恢复默认舵机速度并回姿态2站立 */
const char *Balance_Stop(void);

/* 是否处于平衡模式（含采基准阶段） */
uint8_t Balance_Active(void);

/* 主循环每次调用：状态机 + 闭环控制（内部自带节拍） */
void Balance_Tick(void);

#endif /* __BALANCE_H */
